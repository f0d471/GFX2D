#!/usr/bin/env python3
"""Bake HALTTIME's faceted humanoid poses and viewmodel; no runtime tessellation."""
import argparse
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
OUTPUT = ROOT / 'Main/sw/apps/game/gfx2dGame/src/sh_mesh.h'


def unit(v):
    length = math.sqrt(sum(x*x for x in v))
    if length < 1e-9:
        raise ValueError('degenerate mesh normal')
    return tuple(x/length for x in v)


def cross(a, b):
    return (a[1]*b[2]-a[2]*b[1], a[2]*b[0]-a[0]*b[2], a[0]*b[1]-a[1]*b[0])


class Mesh:
    def __init__(self):
        self.vertices, self.faces, self.normals, self.materials = [], [], [], []

    def triangle(self, ids, outward, material):
        a, b, c = (self.vertices[i] for i in ids)
        normal = cross(tuple(b[k]-a[k] for k in range(3)), tuple(c[k]-a[k] for k in range(3)))
        if sum(normal[k]*outward[k] for k in range(3)) < 0:
            ids = (ids[0], ids[2], ids[1])
            normal = tuple(-x for x in normal)
        self.faces.append(ids)
        self.normals.append(tuple(round(x*127) for x in unit(normal)))
        self.materials.append(material)

    def loft(self, rings, sides, material, phase=0):
        """Rings in centimeters: center xyz, two cross-section radii."""
        base = len(self.vertices)
        for i, r in enumerate(rings):
            before, after = rings[max(0, i-1)], rings[min(len(rings)-1, i+1)]
            tangent = unit(tuple(after[k]-before[k] for k in range(3)))
            ref = (0, 0, 1) if abs(tangent[0]) > .88 else (1, 0, 0)
            dot = sum(ref[k]*tangent[k] for k in range(3))
            u = unit(tuple(ref[k]-dot*tangent[k] for k in range(3)))
            w = cross(tangent, u)
            for j in range(sides):
                angle = (j/sides+phase)*math.tau
                self.vertices.append(tuple(round((r[k]+u[k]*math.cos(angle)*r[3]+
                    w[k]*math.sin(angle)*r[4])*1024/100) for k in range(3)))
        for i in range(len(rings)-1):
            for j in range(sides):
                ids = (base+i*sides+j, base+(i+1)*sides+j,
                       base+(i+1)*sides+(j+1)%sides, base+i*sides+(j+1)%sides)
                center = tuple((rings[i][k]+rings[i+1][k])*1024/200 for k in range(3))
                outward = tuple(sum(self.vertices[v][k] for v in ids)/4-center[k] for k in range(3))
                self.triangle(ids[:3], outward, material)
                self.triangle((ids[0], ids[2], ids[3]), outward, material)
        for i, near in ((0, 1), (len(rings)-1, len(rings)-2)):
            outward = tuple(rings[i][k]-rings[near][k] for k in range(3))
            for j in range(1, sides-1):
                self.triangle((base+i*sides, base+i*sides+j, base+i*sides+j+1), outward, material)


def humanoid(swing):
    m = Mesh()
    bob = abs(swing)//8
    # Pelvis, waist, rib cage, shoulders and neck form one continuous skin.
    m.loft([(0,86+bob,0,14,9),(0,108+bob,1,13,9),(0,128+bob,1,20,11),
            (0,139+bob,0,22,9),(0,148+bob,0,5,5)], 6, 0)
    # Brow/cheek/chin are deliberate silhouette changes, not spherical rings.
    m.loft([(0,148+bob,1,5,5),(0,155+bob,3,8,7),
            (0,168+bob,1,9,8),(0,174+bob,0,3,3)], 6, 0)
    for side in (-1, 1):
        step = swing*side
        m.loft([(side*9,91+bob,0,8,8),(side*10,48,step,6,6),
                (side*10,9,-step/2,4,4)], 4, 1, .125)
        m.loft([(side*10,5,-step/2+4,5,10),(side*10,13,-step/2,4,5)], 4, 1, .125)
    m.loft([(20,136+bob,0,7,7),(25,119+bob,20,6,6),(11,142+bob,40,4,4)], 4, 0, .125)
    m.loft([(-20,136+bob,0,7,7),(-23,117+bob,18,6,6),(5,141+bob,39,4,4)], 4, 0, .125)
    m.loft([(9,141+bob,39,4,4),(10,143+bob,47,4,4)], 4, 0, .125)
    m.loft([(10,146+bob,41,3,3),(10,146+bob,63,3,3)], 4, 2, .125)
    return m


def weapon():
    m = Mesh()
    # Octagonal slide/barrel with readable bevel highlights, a raked grip and glove.
    m.loft([(24,-27,-40,3.2,3.2),(24,-27,-44,4.2,4.2),
            (24,-27,-70,4.2,4.2),(24,-27,-74,3.2,3.2)], 6, 2)
    m.loft([(24,-27,-74,2.3,2.3),(24,-27,-76,2.3,2.3)], 6, 2)
    m.loft([(24,-30,-44,3.2,4),(24,-43,-38,3.2,3)], 4, 2, .125)
    m.loft([(24,-34,-42,5,5),(25,-43,-36,5.5,5),
            (29,-61,-19,7,7)], 5, 2)
    m.vertices = [(x, y+80, z-60) for x, y, z in m.vertices]
    return m


def generated():
    poses = [humanoid(s) for s in range(-16, 17)]
    gun = weapon()
    first = poses[0]
    assert len(first.vertices) < 256 and len(gun.vertices) < 256
    assert all(m.faces == first.faces and m.materials == first.materials for m in poses)
    def array(name, ctype, dimensions, rows):
        return 'static const '+ctype+' '+name+dimensions+' = {\n'+',\n'.join(rows)+'\n};\n'
    def triples(values):
        return '{'+','.join('{'+','.join(map(str, v))+'}' for v in values)+'}'
    text = ('/* Generated by Main/tools/assets/gen_sh_mesh.py; positions 1/1024 m, normals /127. */\n'
            '#ifndef GFX2D_SH_MESH_H\n#define GFX2D_SH_MESH_H\n'
            f'#define SH_MESH_VERTICES {len(first.vertices)}u\n'
            f'#define SH_MESH_FACES {len(first.faces)}u\n'
            f'#define SH_GUN_VERTICES {len(gun.vertices)}u\n'
            f'#define SH_GUN_FACES {len(gun.faces)}u\n')
    text += array('sh_mesh_vertices', 'int16_t', '[33][SH_MESH_VERTICES][3]', [triples(m.vertices) for m in poses])
    text += array('sh_mesh_normals', 'int8_t', '[33][SH_MESH_FACES][3]', [triples(m.normals) for m in poses])
    for name, m in [('sh_mesh', first), ('sh_gun', gun)]:
        text += array(name+'_faces', 'uint8_t', f'[{len(m.faces)}][3]', [','.join('{'+','.join(map(str, f))+'}' for f in m.faces)])
        text += array(name+'_materials', 'uint8_t', f'[{len(m.faces)}]', [','.join(map(str, m.materials))])
    text += array('sh_gun_vertices', 'int16_t', '[SH_GUN_VERTICES][3]', [','.join('{'+','.join(map(str, v))+'}' for v in gun.vertices)])
    text += array('sh_gun_normals', 'int8_t', '[SH_GUN_FACES][3]', [','.join('{'+','.join(map(str, v))+'}' for v in gun.normals)])
    return text+'#endif\n'


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check', action='store_true')
    args = p.parse_args()
    text = generated()
    if args.check:
        if OUTPUT.read_text(encoding='utf-8') != text:
            raise SystemExit('SH mesh header is stale')
    else:
        OUTPUT.write_text(text, encoding='utf-8', newline='\n')
    print('SH MESH GENERATOR PASS 33 poses, indexed faceted humanoid and weapon')


if __name__ == '__main__':
    main()
